# Matches 1m01, 1M01, 1m04a, 1s01, 101m01 and 1m01s.
DEFAULT_CUE_NUMBER_PATTERN = r"^\d{1,3}[mMsS]\d{1,3}[a-zA-Z]?[sS]?$"
# "Any cue number": anything but blank.
ANY_CUE_NUMBER_PATTERN = r"^.+$"


def global_views() -> list[dict[str, object]]:
    """Returns the seeded global views as View field values.

    Each sorts by IN within each picture, but Cue Sheet, which sorts by
    sequence number.
    """
    rows: list[dict[str, object]] = []
    for order, (name, _preset) in enumerate(VIEW_PRESETS):
        sort_by = "sequence_number" if name == "Cue Sheet" else "tc_in"
        rows.append(
            {
                "name": name,
                "order": order,
                "columns": [{"id": column} for column in VIEW_COLUMNS[name]],
                "sort": [{"id": sort_by, "dir": "asc"}],
                "filter": {},
            }
        )
    return rows


