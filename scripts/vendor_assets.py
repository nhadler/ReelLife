"""Copies pinned third-party front-end files into cues/static/cues/vendor.

JS and fonts are served from our own origin (the CSP allows
nothing else), pinned by version with checksums in vendor/VERSIONS.
Versions come from package.json; run `npm ci` first, then
`uv run python scripts/vendor_assets.py` (or `just vendor`).
"""

import hashlib
import json
import pathlib
import shutil

ROOT = pathlib.Path(__file__).resolve().parents[1]
NODE = ROOT / "node_modules"
VENDOR = ROOT / "cues" / "static" / "cues" / "vendor"

# package -> [(file inside the package, name in vendor/)]
FILES = {
    "htmx.org": [
        ("dist/htmx.min.js", "htmx.min.js"),
        ("LICENSE", "htmx.LICENSE"),
    ],
    "@alpinejs/csp": [
        ("dist/cdn.min.js", "alpine-csp.min.js"),
    ],
    "ag-grid-community": [
        # The noStyle build: the default one also injects AG Grid's legacy
        # CSS themes at load time, as <style> elements without the CSP
        # nonce. We theme through the Theming API, which applies the nonce.
        ("dist/ag-grid-community.min.noStyle.js", "ag-grid-community.min.js"),
        ("LICENSE.txt", "ag-grid-community.LICENSE"),
    ],
    "@fontsource-variable/instrument-sans": [
        (
            "files/instrument-sans-latin-wght-normal.woff2",
            "instrument-sans-latin-wght.woff2",
        ),
        (
            "files/instrument-sans-latin-ext-wght-normal.woff2",
            "instrument-sans-latin-ext-wght.woff2",
        ),
        ("LICENSE", "instrument-sans.LICENSE"),
    ],
    "@fontsource/ibm-plex-mono": [
        (
            "files/ibm-plex-mono-latin-400-normal.woff2",
            "ibm-plex-mono-400.woff2",
        ),
        (
            "files/ibm-plex-mono-latin-500-normal.woff2",
            "ibm-plex-mono-500.woff2",
        ),
        ("LICENSE", "ibm-plex-mono.LICENSE"),
    ],
}


def sha256(path: pathlib.Path) -> str:
    """Returns a file's SHA-256 hex digest."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    """Copies the files and rewrites VERSIONS."""
    VENDOR.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Vendored front-end files: package, version, licence, file, sha256.",
        "# Generated by scripts/vendor_assets.py; don't edit by hand.",
    ]
    for package, files in FILES.items():
        meta = json.loads((NODE / package / "package.json").read_text())
        for source, name in files:
            target = VENDOR / name
            shutil.copyfile(NODE / package / source, target)
            lines.append(
                f"{package} {meta['version']} {meta.get('license', '?')} "
                f"{name} {sha256(target)}"
            )
    (VENDOR / "VERSIONS").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Vendored {len(lines) - 2} files into {VENDOR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
